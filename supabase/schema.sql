create extension if not exists pgcrypto;

-- ---------- 文章（管理员发布的内容存这里）----------
create table if not exists public.posts (
  slug       text primary key,
  cat        text not null default 'other',
  title      text not null,
  date       date not null,
  byline     text,
  excerpt    text,
  body       text not null,
  sort_order integer not null default 999,
  published  boolean not null default true,
  updated_at timestamptz not null default now()
);

alter table public.posts enable row level security;
drop policy if exists "posts readable" on public.posts;
create policy "posts readable" on public.posts
  for select using (published = true);

-- ---------- 管理员密钥（只存 sha256，不存明文）----------
create table if not exists public.admin_keys (
  key_hash   text primary key,
  label      text,
  enabled    boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.admin_keys enable row level security;
-- 不建任何策略 = 前端读不到，只有下面的 definer 函数能查

-- ---------- 管理员会话（登录后 24 小时有效）----------
create table if not exists public.admin_sessions (
  token      uuid primary key default gen_random_uuid(),
  key_hash   text not null,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);
alter table public.admin_sessions enable row level security;

-- ---------- 点赞 ----------
create table if not exists public.post_likes (
  slug  text primary key,
  likes integer not null default 0
);

-- ---------- 评论 ----------
create table if not exists public.post_comments (
  id         bigint generated by default as identity primary key,
  slug       text not null,
  name       text not null default '匿名',
  body       text not null,
  approved   boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists post_comments_slug_idx
  on public.post_comments (slug, approved, created_at desc);

-- ============================================================
-- 管理函数
-- ============================================================

-- 用密钥换 token（密钥错则返回 null）
create or replace function public.admin_login(p_key text)
returns uuid
language plpgsql security definer set search_path = public, extensions
as $$
declare
  v_hash  text := encode(digest(p_key, 'sha256'), 'hex');
  v_token uuid;
begin
  if not exists (
    select 1 from public.admin_keys where key_hash = v_hash and enabled
  ) then
    return null;
  end if;

  insert into public.admin_sessions (key_hash, expires_at)
  values (v_hash, now() + interval '24 hours')
  returning token into v_token;

  return v_token;
end;
$$;

-- 校验 token
create or replace function public.admin_check(p_token uuid)
returns boolean
language sql security definer set search_path = public
as $$
  select exists (
    select 1 from public.admin_sessions
    where token = p_token and expires_at > now()
  );
$$;

-- 新建 / 覆盖一篇文章
create or replace function public.admin_save_post(
  p_token   uuid,
  p_slug    text,
  p_title   text,
  p_cat     text,
  p_date    date,
  p_excerpt text,
  p_byline  text,
  p_body    text,
  p_order   integer default 999
)
returns boolean
language plpgsql security definer set search_path = public
as $$
begin
  if not public.admin_check(p_token) then
    raise exception 'unauthorized';
  end if;

  insert into public.posts (slug, cat, title, date, excerpt, byline, body, sort_order, published, updated_at)
  values (p_slug, coalesce(p_cat,'other'), p_title, p_date, p_excerpt, p_byline, p_body,
          coalesce(p_order, 999), true, now())
  on conflict (slug) do update set
    cat        = excluded.cat,
    title      = excluded.title,
    date       = excluded.date,
    excerpt    = excluded.excerpt,
    byline     = excluded.byline,
    body       = excluded.body,
    sort_order = excluded.sort_order,
    published  = true,
    updated_at = now();

  return true;
end;
$$;

-- 删除文章
create or replace function public.admin_delete_post(p_token uuid, p_slug text)
returns boolean
language plpgsql security definer set search_path = public
as $$
begin
  if not public.admin_check(p_token) then raise exception 'unauthorized'; end if;
  delete from public.posts where slug = p_slug;
  return true;
end;
$$;

-- 删除评论
create or replace function public.admin_delete_comment(p_token uuid, p_id bigint)
returns boolean
language plpgsql security definer set search_path = public
as $$
begin
  if not public.admin_check(p_token) then raise exception 'unauthorized'; end if;
  delete from public.post_comments where id = p_id;
  return true;
end;
$$;

-- 退出登录
create or replace function public.admin_logout(p_token uuid)
returns void
language plpgsql security definer set search_path = public
as $$
begin
  delete from public.admin_sessions where token = p_token;
end;
$$;

-- ---------- 点赞自增 ----------
create or replace function public.increment_like(p_slug text)
returns integer
language plpgsql security definer set search_path = public
as $$
declare n integer;
begin
  insert into public.post_likes (slug, likes) values (p_slug, 1)
  on conflict (slug) do update set likes = public.post_likes.likes + 1
  returning likes into n;
  return n;
end;
$$;

-- ============================================================
-- 行级安全策略
-- ============================================================

alter table public.post_likes    enable row level security;
alter table public.post_comments enable row level security;

drop policy if exists "likes readable" on public.post_likes;
create policy "likes readable" on public.post_likes
  for select using (true);

drop policy if exists "comments readable" on public.post_comments;
create policy "comments readable" on public.post_comments
  for select using (approved = true);

drop policy if exists "comments insertable" on public.post_comments;
create policy "comments insertable" on public.post_comments
  for insert
  with check (
    char_length(body) between 1 and 800
    and char_length(name) <= 20
    and approved = false
  );

-- ============================================================
-- 权限：匿名用户只能调用上面这些函数
-- ============================================================

grant execute on function public.admin_login(text)          to anon;
grant execute on function public.admin_check(uuid)          to anon;
grant execute on function public.admin_save_post(uuid,text,text,text,date,text,text,text,integer) to anon;
grant execute on function public.admin_delete_post(uuid,text)   to anon;
grant execute on function public.admin_delete_comment(uuid,bigint) to anon;
grant execute on function public.admin_logout(uuid)         to anon;
grant execute on function public.increment_like(text)       to anon;

